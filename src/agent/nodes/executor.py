import json
import logging
from langchain_core.messages import SystemMessage
from src.agent.state import AgentState
from src.agent.prompts.prompts import EXECUTOR_PROMPT

logger = logging.getLogger(__name__)

def get_executor_node(llm, tools):
    """
    TECHNICIAN (Technician): Executes tasks generated by the Architect using available tools.
    """
    async def executor_node(state: AgentState) -> dict:
        print(f"🔧 EXECUTING: Technician preparing tool sequence...")
        
        tool_descriptions = "\n".join([f"- {t.name}: {t.description}" for t in tools])
        task_list_str = json.dumps(state.get("task_list", []), ensure_ascii=False, indent=2)
        
        # 1. Format Prompt
        prompt = EXECUTOR_PROMPT.format(
            tool_descriptions=tool_descriptions,
            task_list_str=task_list_str
        )
        
        try:
            response = await llm.ainvoke([
                SystemMessage(content=prompt),
                *state["messages"]
            ])
            
            # 2. Parse Tool Calls
            from src.agent.utils import parse_json_from_llm
            parsed = parse_json_from_llm(response.content)
            
            tool_calls = parsed.get("tool_calls", [])
            next_node = parsed.get("next_node", "tools")
            monologue = parsed.get("internal_monologue", "")
            
            # 3. Handle Empty Calls - if executor suggests 'synthesize' or no tools
            if not tool_calls and next_node == "tools":
                next_node = "synthesize"
                
            logger.info(f"EXECUTOR: Next={next_node}, Calls={len(tool_calls)}")
            return {
                "tool_calls": tool_calls,
                "next_node": next_node,
                "internal_monologue": monologue
            }
            
        except Exception as e:
            logger.error(f"EXECUTOR_ERROR: {e}")
            return {"next_node": "synthesize"} # Fallback to answer if tech fails

    return executor_node
